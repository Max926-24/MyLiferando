-- Заведения-отправители
CREATE TABLE client
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    address     VARCHAR(255) NOT NULL,
    email       VARCHAR(255) NOT NULL,
    phone       VARCHAR(20)  NOT NULL,
    client_type VARCHAR(255) NOT NULL,
    legal_type  VARCHAR(255) NOT NULL,
    inn         VARCHAR(12),
    CONSTRAINT uq_client_email UNIQUE (email),
    CONSTRAINT uq_client_inn UNIQUE (inn)
);

-- Курьеры
CREATE TABLE courier
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(255) NOT NULL,
    phone     VARCHAR(20)  NOT NULL,
    status    VARCHAR(255) NOT NULL,
    transport VARCHAR(255) NOT NULL,
    CONSTRAINT uq_courier_phone UNIQUE (phone)
);

-- Заказы: создаётся последней, потому что ссылается на client и courier
CREATE TABLE orders
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description      VARCHAR(255),
    delivery_address VARCHAR(255) NOT NULL,
    recipient_name   VARCHAR(255) NOT NULL,
    recipient_phone  VARCHAR(20)  NOT NULL,
    status           VARCHAR(255) NOT NULL,
    client_id        BIGINT       NOT NULL,
    courier_id       BIGINT,
    created_at       TIMESTAMP    NOT NULL,
    delivered_at     TIMESTAMP,
    CONSTRAINT fk_orders_client FOREIGN KEY (client_id) REFERENCES client (id),
    CONSTRAINT fk_orders_courier FOREIGN KEY (courier_id) REFERENCES courier (id)
);
